window.countryShort = function (k, y) {
  const S = { DE: y < 1919 ? 'ГЕРМАНИЯ' : y < 1933 ? 'ГЕРМАНИЯ' : 'ГЕРМАНСКИЙ РЕЙХ', AH: 'АВСТРО-ВЕНГРИЯ', RU: y < 1917 ? 'РОССИЙСКАЯ ИМПЕРИЯ' : y < 1923 ? 'СОВЕТСКАЯ РОССИЯ' : 'СССР',
    TR: y < 1922 ? 'ОСМАНСКАЯ ИМПЕРИЯ' : 'ТУРЦИЯ', GB: 'ВЕЛИКОБРИТАНИЯ', YU: y < 1929 ? 'КОР. СХС' : 'ЮГОСЛАВИЯ', SR: 'ЮГ РОССИИ', CS: 'ЧЕХОСЛОВАКИЯ',
    FI: 'ФИНЛЯНДИЯ', SY: 'СИРИЯ', PS: 'ПАЛЕСТИНА', IQ: 'ИРАК', DZA: 'АЛЖИР', TN: 'ТУНИС', LY: 'ЛИВИЯ', DZ: 'ДАНЦИГ' };
  return S[k] || window.countryName(k, y).toUpperCase();
};
